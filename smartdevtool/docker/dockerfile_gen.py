"""Dockerfile generator using Jinja2 templates and layer-cache friendly ordering.

Adheres strictly to secrets discipline: declares required environment variable NAMES only,
never commits or bakes secret values into any image layer.
Consults LLM for base-image selection when available, with a deterministic offline heuristic fallback.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Any
from jinja2 import Template

from smartdevtool.llm.client import LLMClient
from smartdevtool.llm.prompts import (
    DOCKER_BASE_IMAGE_SYSTEM_PROMPT,
    DOCKER_BASE_IMAGE_USER_TEMPLATE,
)

DOCKERFILE_TEMPLATE = """# Generated by SmartDevTool
FROM {{ base_image }}

ENV PYTHONUNBUFFERED=1 \\
    PYTHONDONTWRITEBYTECODE=1

WORKDIR /app

{% if system_packages %}
# System dependencies
RUN apt-get update && apt-get install -y --no-install-recommends \\
    {{ system_packages|join(' ') }} \\
    && rm -rf /var/lib/apt/lists/*
{% endif %}

# Layer-cache friendly: copy requirements and install dependencies before application code
COPY {{ requirements_file }} .
RUN pip install --no-cache-dir -r {{ requirements_file }}

# Copy application source code
COPY . .

# Environment variable declarations (variable names only, never secrets)
{% for var_name in env_vars %}
ENV {{ var_name }}=""
{% endfor %}

{% if expose_port %}
EXPOSE {{ expose_port }}
{% endif %}

CMD ["{{ cmd }}", "{{ entrypoint }}"]
"""


class DockerfileGenerator:
    """Generates layer-cache optimized Dockerfiles tailored to project dependencies."""

    def __init__(self, llm_client: LLMClient | None = None) -> None:
        self.llm_client = llm_client

    def select_base_image(
        self, dependencies: list[str], python_version: str = "3.11"
    ) -> tuple[str, list[str], str]:
        """Select appropriate base image via LLM or deterministic heuristic.

        Returns (base_image_tag, system_packages, reasoning).
        """
        # Strategy 1: LLM decision (consulted for this ONE decision)
        if self.llm_client and self.llm_client.available:
            prompt = DOCKER_BASE_IMAGE_USER_TEMPLATE.format(
                dependencies=", ".join(dependencies) or "standard python packages"
            )
            data = self.llm_client.complete_json(
                system_prompt=DOCKER_BASE_IMAGE_SYSTEM_PROMPT,
                user_prompt=prompt,
            )
            if data and isinstance(data, dict) and "base_image" in data:
                return (
                    data["base_image"],
                    data.get("system_packages", []),
                    data.get("reasoning", "Selected by LLM based on dependencies"),
                )

        # Strategy 2: Deterministic heuristic fallback
        heavy_cuda_pkgs = {"torch", "torchvision", "torchaudio", "tensorflow", "jax", "cupy"}
        norm_deps = {re.split(r"[=<>~!@; \t]", d.strip())[0].lower().replace("_", "-") for d in dependencies}

        if any(pkg in norm_deps for pkg in heavy_cuda_pkgs):
            return (
                "pytorch/pytorch:2.1.0-cuda12.1-cudnn8-runtime",
                ["build-essential", "curl"],
                "Detected ML/GPU dependencies; selected PyTorch CUDA runtime base image",
            )

        return (
            f"python:{python_version}-slim",
            [],
            "Standard Python project; selected official slim base image",
        )

    def generate(
        self,
        dependencies: list[str],
        requirements_file: str = "requirements.txt",
        env_vars: list[str] | None = None,
        expose_port: int | None = None,
        cmd: str = "python",
        entrypoint: str = "main.py",
        python_version: str = "3.11",
    ) -> str:
        """Render Dockerfile content."""
        base_image, sys_packages, _ = self.select_base_image(
            dependencies=dependencies, python_version=python_version
        )

        clean_env_vars = sorted(list(set(env_vars or [])))

        template = Template(DOCKERFILE_TEMPLATE, trim_blocks=True, lstrip_blocks=True)
        return template.render(
            base_image=base_image,
            system_packages=sys_packages,
            requirements_file=requirements_file,
            env_vars=clean_env_vars,
            expose_port=expose_port,
            cmd=cmd,
            entrypoint=entrypoint,
        )

    def write(
        self,
        output_path: Path | str,
        dependencies: list[str],
        requirements_file: str = "requirements.txt",
        env_vars: list[str] | None = None,
        expose_port: int | None = None,
        cmd: str = "python",
        entrypoint: str = "main.py",
    ) -> Path:
        """Generate and save Dockerfile to disk."""
        target = Path(output_path).resolve()
        content = self.generate(
            dependencies=dependencies,
            requirements_file=requirements_file,
            env_vars=env_vars,
            expose_port=expose_port,
            cmd=cmd,
            entrypoint=entrypoint,
        )
        with open(target, "w", encoding="utf-8") as f:
            f.write(content)
        return target
